# Entrada de Dados

raio = input("Me dê o raio de um círculo! > ")

# Processamento de Dados

area = 3.14 * (float(raio) ** 2)

# Saída de Dados
print("A área do círculo é, aproximadamente %.2f!" %(float(area)))
